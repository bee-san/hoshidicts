// Writes src/languages/case_tables.cpp: what the engine's `case` step adds to
// utf8proc's simple case mappings so that it gives the results of
// JavaScript's toLowerCase and toUpperCase (docs/languages.md, section 6.2):
//
// - every code point whose JavaScript lower- or uppercase is not one code
//   point (the unconditional entries of SpecialCasing.txt: ß -> SS,
//   İ -> i + U+0307, ŉ -> ʼN, ...);
// - the Cased and Case_Ignorable properties, for Final_Sigma
//   (ΟΔΟΣ -> οδος).
//
//   node src/languages/generate_case_tables.mjs [--check]
//
// --check compares every code point's single-code-point mapping with the
// table it reads from stdin (one "<cp> <lower> <upper>" line per code point,
// in hex, as `case-mapping-dump` prints utf8proc's), so a difference between
// Node's and utf8proc's simple mappings is caught.

import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const output = fileURLToPath(new URL('case_tables.cpp', import.meta.url));

function hex(cp) {
    return `0x${cp.toString(16).toUpperCase()}`;
}

function ranges(regExp) {
    const out = [];
    let first = -1;
    for (let cp = 0; cp <= 0x10FFFF; ++cp) {
        if (cp >= 0xD800 && cp <= 0xDFFF) {
            if (first >= 0) {
                out.push([first, cp - 1]);
                first = -1;
            }
            continue;
        }
        if (regExp.test(String.fromCodePoint(cp))) {
            if (first < 0) { first = cp; }
        } else if (first >= 0) {
            out.push([first, cp - 1]);
            first = -1;
        }
    }
    if (first >= 0) { out.push([first, 0x10FFFF]); }
    return out;
}

function specials(map) {
    const out = [];
    for (let cp = 0; cp <= 0x10FFFF; ++cp) {
        if (cp >= 0xD800 && cp <= 0xDFFF) { continue; }
        const result = [...map(String.fromCodePoint(cp))].map((c) => c.codePointAt(0));
        if (result.length !== 1) { out.push([cp, result]); }
    }
    return out;
}

if (process.argv.includes('--check')) {
    let differences = 0;
    for (const line of readFileSync(0, 'utf8').split('\n')) {
        if (line === '') { continue; }
        const [cp, lower, upper] = line.split(' ').map((v) => Number.parseInt(v, 16));
        const s = String.fromCodePoint(cp);
        const jsLower = [...s.toLowerCase()].map((c) => c.codePointAt(0));
        const jsUpper = [...s.toUpperCase()].map((c) => c.codePointAt(0));
        if (jsLower.length === 1 && jsLower[0] !== lower) {
            console.error(`lower ${hex(cp)}: Node ${hex(jsLower[0])}, utf8proc ${hex(lower)}`);
            ++differences;
        }
        if (jsUpper.length === 1 && jsUpper[0] !== upper) {
            console.error(`upper ${hex(cp)}: Node ${hex(jsUpper[0])}, utf8proc ${hex(upper)}`);
            ++differences;
        }
    }
    console.log(`${differences} differences (Node ${process.version}, Unicode ${process.versions.unicode})`);
    process.exit(differences === 0 ? 0 : 1);
}

const lower = specials((s) => s.toLowerCase());
const upper = specials((s) => s.toUpperCase());
const cased = ranges(/^\p{Cased}$/u);
const ignorable = ranges(/^\p{Case_Ignorable}$/u);

const special = (name, entries) => {
    const rows = entries.map(([cp, out]) => `    {${hex(cp)}, {${[...out, 0, 0, 0].slice(0, 3).map(hex).join(', ')}}, ${out.length}},`);
    return `extern const SpecialCase ${name}[] = {\n${rows.join('\n')}\n};\nextern const size_t ${name}_count = ${entries.length};\n`;
};
const rangeTable = (name, entries) => {
    const rows = [];
    for (let i = 0; i < entries.length; i += 6) {
        rows.push(`    ${entries.slice(i, i + 6).map(([a, b]) => `{${hex(a)}, ${hex(b)}}`).join(', ')},`);
    }
    return `extern const CaseRange ${name}[] = {\n${rows.join('\n')}\n};\nextern const size_t ${name}_count = ${entries.length};\n`;
};

const text = `// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by src/languages/generate_case_tables.mjs with Node ${process.version}
// (Unicode ${process.versions.unicode}). Do not edit.
#include "case_mapping.hpp"

namespace hoshidicts::lang::case_tables {

${special('lower_special', lower)}
${special('upper_special', upper)}
${rangeTable('cased', cased)}
${rangeTable('case_ignorable', ignorable)}
}  // namespace hoshidicts::lang::case_tables
`;
writeFileSync(output, text);
console.log(`wrote ${output}: ${lower.length} lower and ${upper.length} upper special cases, ${cased.length} Cased and ${ignorable.length} Case_Ignorable ranges`);
