#!/usr/bin/env node
// SPDX-License-Identifier: GPL-3.0-or-later
// Writes the "guards" rows at the end of languages/eo/tests/defaults.tsv (and,
// for the optional transform, of tests/cases.tsv), so that removing a stem
// constraint or a condition, lowering a minimum by one, or letting an
// excluded stem back in fails the conformance test (docs/languages.md 14
// step 7). Run from the repository root after
// build-final.mjs:
//
//   node languages/eo/sources/build-guards.mjs
//
// Rows are built from each rule's own affixes on a stem made of letters no
// affix starts or ends with (brst…). A rule that excluded-stems.mjs split by
// the text its stem starts with has that text at the start of its stem.
//
// - Every rule: a positive row, the form → the rule's output, with the
//   rule's part of speech in the rule column (when it gives one) and its
//   transform as the trace, so that a rule removed, or giving another part
//   of speech, fails.
// - stemCharacters [^ ]: a stem with a space, "mi " before a suffix rule's
//   form (mi legas must not give mi legi) and inside a circumfix's or
//   prefix's stem (malmi bona must not give mi bona).
// - stemMinLength n: a stem one letter shorter (ĝis must not give ĝii), and
//   a positive row with a stem of exactly n letters.
// - stemNotStartsWith with the class {upper}: the form with a capital stem,
//   once with B and once with Ĉ (Dometo must not give Domo; Ĉapeloj must not
//   give Ĉapelo).
// - The exact stems excluded-stems.mjs lists: a negative row for each, the
//   excluded word → the rule's output (kate must not give kata).
// - conditionsOut: a negative row whose rule column names a part of speech
//   the rule does not give (brsas → brsi is a verb, so not a noun); for a
//   verb prefix, also after the past ending (elbrsis), where its Yomitan twin
//   does not apply.
// - conditionsIn: a positive row through a prefix rule that gives that
//   condition (nebrsanta → ne → brsanta [adj] → -ant- → brsi), which fails
//   when the rule loses its conditionsIn, since a rule with none takes only
//   texts without conditions (docs/languages.md 7.2). The prefixes are own
//   rules without a Yomitan twin (ne-, ge-, re-).
//
// A candidate the final rules do not pass is left out (a positive whose term
// is not reached with its trace, or a negative whose term another rule
// reaches): the script deinflects every candidate with hoshidicts-cli and
// keeps the rows that pass.

import {execFileSync} from 'node:child_process';
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {EXCLUDED_STEMS, exclusionKey} from './excluded-stems.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const cli = join(root, 'build', 'hoshidicts-cli');
const final = JSON.parse(readFileSync(join(here, '..', 'transforms.json'), 'utf8'));
const casesFile = join(here, '..', 'tests', 'cases.tsv');
const defaultsFile = join(here, '..', 'tests', 'defaults.tsv');
const MARK = '# --- guards: generated by sources/build-guards.mjs; edit that script, not these rows ---';

// A stem of the given length that starts with `start`, filled with letters
// no affix starts or ends with.
const stemOf = (n, start = '') => (start + 'brst'.repeat(5)).slice(0, Math.max(n, start.length));
const capital = (s, letter) => letter + s.slice(1);

// A stem for a rule: at least n letters, starting with the rule's
// stemStartsWithText, and ending as its stemNotEndsWith class allows (a
// split copy takes only stems that end, or do not end, with given letters).
function stemFor(rule, n) {
    const start = rule.stemStartsWithText ?? '';
    let stem = stemOf(n, start);
    // A first copy whose stemNotStartsWith class leaves some first letters
    // to the split copies takes a stem that starts with another letter.
    const not = (rule.stemNotStartsWith ?? '').replace('{upper}', '');
    if (start === '' && not.includes(stem[0])) {
        const first = [...'rstpkdl'].find((c) => !not.includes(c));
        stem = first + stem.slice(1);
    }
    if (rule.stemEndsWith) {
        stem = stemOf(Math.max(n, start.length + 1) - 1, start) + rule.stemEndsWith[1];
    } else if (rule.stemNotEndsWith) {
        const letters = rule.stemNotEndsWith.slice(1, -1);
        while (letters.includes(stem.at(-1))) { stem += 'r'; }
    }
    return stem;
}

// The four parts of speech of the pack's conditions (none has
// subConditions), and the own prefix rule that feeds each: it keeps the
// word's ending and gives that condition.
const PARTS_OF_SPEECH = ['n', 'v', 'adj', 'adv'];
const FEEDERS = {
    adj: {id: 'ne', prefix: 'ne', ending: 'a'},
    adv: {id: 'ne', prefix: 'ne', ending: 'e'},
    n: {id: 'ge', prefix: 'ge', ending: 'o'},
    v: {id: 're', prefix: 're', ending: 'i'},
};

const candidates = [];
const optionalRows = new Set();
for (const t of final.transforms) {
    const done = new Set();
    const before = candidates.length;
    for (const rule of t.rules) {
        if (rule.type !== 'suffix' && rule.type !== 'circumfix' && rule.type !== 'prefix') { continue; }
        const make = (stem) => {
            if (rule.type === 'suffix') { return [stem + rule.inflected, stem + rule.deinflected]; }
            if (rule.type === 'prefix') { return [rule.inflected + stem, rule.deinflected + stem]; }
            return [rule.inflectedPrefix + stem + rule.inflectedSuffix, rule.deinflectedPrefix + stem + rule.deinflectedSuffix];
        };
        const min = rule.stemMinLength ?? 0;
        const start = rule.stemStartsWithText ?? '';
        const out = rule.conditionsOut ?? [];
        const length = Math.max(min, 3, start.length + 1);
        const stem = stemFor(rule, length);
        const [from, to] = make(stem);
        candidates.push([`rule: ${t.id}`, '1', from, to, out.length === 1 ? out[0] : '*', t.id]);
        // A copy that excluded-stems.mjs split off (it names the text its
        // stem starts with) shares the original's constraints and
        // conditions, whose rows the first copy has; it needs only its own
        // row above and the rows of the excluded stems below.
        const copy = rule.stemStartsWithText !== undefined;
        if (rule.stemCharacters === '[^ ]' && !copy) {
            if (rule.type === 'suffix') {
                candidates.push(['guard: no space in the stem', '0', `mi ${from}`, `mi ${to}`, '*', '*']);
            } else if (start === '') {
                const [f, d] = make(`mi ${stem}`);
                candidates.push(['guard: no space in the stem', '0', f, d, '*', '*']);
            } else {
                const [f, d] = make(`${start} mi ${stem.slice(start.length)}`);
                candidates.push(['guard: no space in the stem', '0', f, d, '*', '*']);
            }
        }
        // A stem of exactly the minimum, which must still be read (so that a
        // minimum raised by one fails a row): luado → lui, irejo → iri.
        if (min >= 2 && !copy) {
            const exact = stemFor(rule, min).slice(0, min);
            if (exact.length === min) {
                const [f, d] = make(exact);
                candidates.push([`rule: ${t.id} (shortest stem)`, '1', f, d, out.length === 1 ? out[0] : '*', t.id]);
            }
        }
        // A stem one letter short; a split copy's start text is already as
        // long as that for the stems its minimum stops.
        if (min >= 1 && min - 1 >= start.length && !copy) {
            const short = stem.slice(0, Math.max(min - 1, 0));
            const [f, d] = make(short);
            if (d !== '' && f !== d) {
                candidates.push([`guard: stem of ${min} letters at least`, '0', f, d, '*', '*']);
            }
        }
        if ((rule.stemNotStartsWith ?? '').includes('{upper}') && !copy) {
            for (const letter of ['B', 'Ĉ']) {
                const [f, d] = make(capital(stemOf(length), letter));
                candidates.push(['guard: no capital stem', '0', f, d, '*', '*']);
            }
        }
        const other = PARTS_OF_SPEECH.find((c) => !out.includes(c));
        if (out.length > 0 && other !== undefined && !copy) {
            candidates.push([`guard: output is ${out.join(' ')}`, '0', from, to, other, '*']);
            if (rule.type === 'circumfix' && rule.inflectedSuffix === 'i') {
                candidates.push([`guard: output is ${out.join(' ')}`, '0', `${from.slice(0, -1)}is`, to, other, '*']);
            }
        }
        const into = rule.conditionsIn ?? [];
        if (into.length === 1 && FEEDERS[into[0]] && from.endsWith(FEEDERS[into[0]].ending) && !copy) {
            const feeder = FEEDERS[into[0]];
            candidates.push([`chain: input is ${into[0]}`, '1', feeder.prefix + from, to, out.length === 1 ? out[0] : '*',
                `${t.id}|${feeder.id}`]);
        }
        // The exact stems excluded from this rule's original.
        const excluded = EXCLUDED_STEMS[exclusionKey(t.id, rule)];
        const key = JSON.stringify([rule.type, rule.inflected, rule.deinflected, rule.inflectedPrefix, rule.inflectedSuffix,
            rule.deinflectedSuffix]);
        if (excluded && !done.has(key)) {
            done.add(key);
            for (const [stem, words] of excluded) {
                const [f, d] = make(stem);
                candidates.push([`guard: excluded stem (${words})`, '0', f, d, '*', '*']);
            }
        }
    }
    if (t.optional) {
        for (let i = before; i < candidates.length; ++i) { optionalRows.add(candidates[i]); }
    }
}

// Keep each row once, and only rows the final rules pass in the file's mode:
// a negative's term is not among the deinflections of the source with a
// condition its rule column accepts, and a positive's term is, with its
// trace and a compatible condition.
// A source with an x-system digraph never reaches the rules as written: the
// processor xSystem replaces it.
const XSYSTEM = /[cghjsuCGHJSU][xX]/;
const seen = new Set();
const unique = candidates.filter((row) => {
    if (XSYSTEM.test(row[2])) { return false; }
    const key = row.join('\t');
    if (seen.has(key)) { return false; }
    seen.add(key);
    return true;
});
const inputs = [...new Set(unique.map(([, , from]) => from))];
const deinflect = (options) => {
    const out = execFileSync(cli, ['--languages', join(root, 'languages'), 'deinflect', 'eo', '--stdin', ...options],
        {input: inputs.join('\n') + '\n', encoding: 'utf8', maxBuffer: 1 << 28});
    return new Map(out.trim().split('\n').map((line) => {
        const d = JSON.parse(line);
        return [d.input, d.results];
    }));
};
// cases.tsv runs with every option on, defaults.tsv with the defaults.
const allOptions = deinflect(['--all-options']);
const defaults = deinflect([]);
const compatible = (r, rule) => rule === '*' || r.conditions.length === 0 || r.conditions.includes(rule);
const passes = (row) => {
    const [, valid, from, to, rule, reasons] = row;
    const results = optionalRows.has(row) ? allOptions : defaults;
    const found = results.get(from).filter((r) => r.text === to);
    if (valid === '1') {
        return found.some((r) => compatible(r, rule) && (reasons === '*' || r.trace.join('|') === reasons));
    }
    return !found.some((r) => compatible(r, rule));
};
const rows = unique.filter(passes);
const skipped = unique.length - rows.length;

// The rows of an optional transform need every option on (cases.tsv); the
// others suit the pack's defaults and go to defaults.tsv, which keeps each
// file under the contract's 2,000 rows (docs/languages.md 3).
function write(file, chosen) {
    const kept = readFileSync(file, 'utf8').split('\n');
    const at = kept.indexOf(MARK);
    const head = (at >= 0 ? kept.slice(0, at) : kept).join('\n').replace(/\n+$/, '');
    const body = chosen.map((row) => row.join('\t')).join('\n');
    writeFileSync(file, `${head}\n${MARK}\n${body}${chosen.length ? '\n' : ''}`);
    console.log(`eo: ${chosen.length} guard rows in ${file}`);
}
write(casesFile, rows.filter((row) => optionalRows.has(row)));
write(defaultsFile, rows.filter((row) => !optionalRows.has(row)));
console.log(`eo: ${skipped} candidates the final rules do not pass, left out`);
