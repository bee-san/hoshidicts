#!/usr/bin/env node
// SPDX-License-Identifier: GPL-3.0-or-later
// Writes the "guards" rows at the end of languages/eo/tests/cases.tsv: one
// negative row for each stem constraint of transforms.json, so that removing
// the constraint, or lowering a minimum by one, fails the conformance test
// (docs/languages.md 14 step 7). Run from the repository root after
// build-final.mjs:
//
//   node languages/eo/sources/build-guards.mjs
//
// For each rule (a cross product's parts taken one at a time) it builds an
// input the constraint alone blocks, from the rule's own affixes:
//
// - stemCharacters [^ ]: a stem with a space, "mi " before a suffix rule's
//   form (mi legas must not give mi legi) and inside a circumfix's stem
//   (malmi bona must not give mi bona);
// - stemMinLength n: a stem of n - 1 letters (n ≥ 2), or of one letter for
//   n = 1, which must not give the rule's output (ĝis must not give ĝii);
// - stemNotStartsWith {upper}: the form with a capital stem (Dometo must not
//   give Domo).
//
// The term of a row is what the rule alone would give. A candidate whose
// term the final rules reach anyway (through another rule) cannot test the
// constraint and is left out: the script deinflects every candidate with
// hoshidicts-cli and keeps the rows that pass.

import {execFileSync} from 'node:child_process';
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const cli = join(root, 'build', 'hoshidicts-cli');
const final = JSON.parse(readFileSync(join(here, '..', 'transforms.json'), 'utf8'));
const casesFile = join(here, '..', 'tests', 'cases.tsv');
const MARK = '# --- guards: generated by sources/build-guards.mjs; edit that script, not these rows ---';

// A stem of the given length made of letters no affix starts or ends with.
const stemOf = (n, upper = false) => {
    const s = 'brst'.repeat(4).slice(0, n);
    return upper && n > 0 ? s[0].toUpperCase() + s.slice(1) : s;
};

const candidates = [];
for (const t of final.transforms) {
    for (const rule of t.rules) {
        if (rule.type !== 'suffix' && rule.type !== 'circumfix' && rule.type !== 'prefix') { continue; }
        const make = (stem) => {
            if (rule.type === 'suffix') { return [stem + rule.inflected, stem + rule.deinflected]; }
            if (rule.type === 'prefix') { return [rule.inflected + stem, rule.deinflected + stem]; }
            return [rule.inflectedPrefix + stem + rule.inflectedSuffix, rule.deinflectedPrefix + stem + rule.deinflectedSuffix];
        };
        const min = rule.stemMinLength ?? 0;
        if (rule.stemCharacters === '[^ ]') {
            // The space goes where the stem is: before a suffix rule's form
            // (mi legas), inside a circumfix's stem (mal mi bona), and after a
            // prefix rule's prefix.
            if (rule.type === 'suffix') {
                const [from, to] = make(stemOf(Math.max(min, 3)));
                candidates.push(['guard: no space in the stem', `mi ${from}`, `mi ${to}`, t.id]);
            } else {
                const [from, to] = make(`mi ${stemOf(Math.max(min, 3))}`);
                candidates.push(['guard: no space in the stem', from, to, t.id]);
            }
        }
        if (min >= 1) {
            const [from, to] = make(stemOf(min - 1));
            if (to !== '' && from !== to) { candidates.push([`guard: stem of ${min} letters at least`, from, to, t.id]); }
        }
        if (rule.stemNotStartsWith === '{upper}') {
            const [from, to] = make(stemOf(Math.max(min, 3), true));
            candidates.push(['guard: no capital stem', from, to, t.id]);
        }
    }
}

// Keep each (source, term) once, and only rows the final rules pass: the
// term is not among the deinflections of the source (with every option on).
const seen = new Set();
const unique = candidates.filter(([, from, to]) => {
    const key = `${from}\t${to}`;
    if (seen.has(key)) { return false; }
    seen.add(key);
    return true;
});
const inputs = [...new Set(unique.map(([, from]) => from))];
const out = execFileSync(cli, ['--languages', join(root, 'languages'), 'deinflect', 'eo', '--stdin', '--all-options'],
    {input: inputs.join('\n') + '\n', encoding: 'utf8'});
const texts = new Map(out.trim().split('\n').map((line) => {
    const d = JSON.parse(line);
    return [d.input, new Set(d.results.map((r) => r.text))];
}));
const rows = unique.filter(([, from, to]) => !texts.get(from).has(to));
const skipped = unique.length - rows.length;

const kept = readFileSync(casesFile, 'utf8').split('\n');
const at = kept.indexOf(MARK);
const head = (at >= 0 ? kept.slice(0, at) : kept).join('\n').replace(/\n+$/, '');
const body = rows.map(([category, from, to]) => `${category}\t0\t${from}\t${to}\t*\t*`).join('\n');
writeFileSync(casesFile, `${head}\n${MARK}\n${body}\n`);
console.log(`eo: ${rows.length} guard rows in ${casesFile} (${skipped} candidates whose term another rule reaches, left out)`);
