"""Writes src/languages/builtin_packs.cpp: the packs built into the library
(docs/languages.md, section 10.1) as byte arrays, so Swift Package builds,
which do not run CMake, have them too.

    python3 tools/embed-packs.py            # writes the file
    python3 tools/embed-packs.py --check    # fails when the file is stale

The language-conformance test also fails when the embedded copy differs from
languages/<code>/. Only Japanese is built in; other packs load at run time
(docs/decisions/0002-packs-load-at-runtime.md).
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "languages" / "builtin_packs.cpp"
BUILTIN = ["ja"]


def byte_array(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    body = "\n".join(lines)
    return f"const unsigned char {name}[] = {{\n{body}\n}};\n"


def render():
    parts = [
        "// SPDX-License-Identifier: GPL-3.0-or-later\n",
        "// Generated by tools/embed-packs.py from languages/" + ", languages/".join(BUILTIN) + ". Do not edit:\n",
        "// change the pack and run python3 tools/embed-packs.py.\n",
        '#include "builtin_packs.hpp"\n\n',
        "namespace hoshidicts::lang {\n\nnamespace {\n",
    ]
    entries = []
    for code in BUILTIN:
        pack = ROOT / "languages" / code
        language = (pack / "language.json").read_bytes()
        transforms_name = json.loads(language.decode("utf-8"))["lookup"].get("transforms")
        transforms = (pack / transforms_name).read_bytes() if transforms_name else b""
        ident = code.replace("-", "_")
        parts.append(byte_array(f"{ident}_language", language))
        parts.append(byte_array(f"{ident}_transforms", transforms) if transforms else f"const unsigned char {ident}_transforms[] = {{0}};\n")
        entries.append(
            f'    {{"{code}", {{reinterpret_cast<const char*>({ident}_language), {len(language)}}}, '
            f'{{reinterpret_cast<const char*>({ident}_transforms), {len(transforms)}}}, '
            f'"{transforms_name or ""}"}},\n'
        )
    parts.append("}  // namespace\n\n")
    parts.append(f"const BuiltinPack builtin_packs[] = {{\n{''.join(entries)}}};\n")
    parts.append(f"const size_t builtin_pack_count = {len(BUILTIN)};\n\n")
    parts.append("}  // namespace hoshidicts::lang\n")
    return "".join(parts)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run python3 tools/embed-packs.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({', '.join(BUILTIN)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
